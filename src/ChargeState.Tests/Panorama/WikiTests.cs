    public async Task Without_a_working_sign_in_nothing_is_sent_and_the_person_is_told()
    {
        using var setup = new Publisher(Editor(Ours("abc")), hash: "abc", signedIn: false);

        (await setup.Wiki.UpdateAsync(setup.Project)).ShouldNotBeNull().ShouldContain("no Panorama sign-in works");
        setup.Handler.Bodies.ShouldBeEmpty();
    }

    private static HttpResponseMessage Json(string body) =>
        new(HttpStatusCode.OK) { Content = new StringContent(body, Encoding.UTF8, "application/json") };

    /// <summary>A WikiPublisher whose Panorama and engine answer from here.</summary>
    private sealed class Publisher : IDisposable
    {
        private readonly TempDirectory _dir = new();

        public Publisher(string? editor, string hash, bool signedIn = true)
        {
            Html = $"<div><p>Progress</p>\n<div id=\"chargestate-wiki\" data-written=\"{hash}\">Generated</div></div>\n";
            Handler = new StubHandler(request => request.RequestUri!.AbsolutePath switch
            {
                "/_webdav/" => Json("""{"files":[]}"""),
                "/login-whoami.api" => WhoAmI(),
                var p when p.EndsWith("/wiki-edit.view", StringComparison.Ordinal) =>
                    editor is null ? new HttpResponseMessage(HttpStatusCode.NotFound) : new HttpResponseMessage(HttpStatusCode.OK) { Content = new StringContent(editor) },
                var p when p.EndsWith("/query-selectRows.api", StringComparison.Ordinal) => Json(Runs),
                var p when p.EndsWith("/wiki-saveWiki.api", StringComparison.Ordinal) => Json("""{"success":true,"wikiProps":{"pageVersionId":18200}}"""),
                _ => new HttpResponseMessage(HttpStatusCode.NotFound),
            });
            var store = new Store();
            if (signedIn)
            {
                store.Entries["PanoramaBridge:https://panoramaweb.org"] = new StoredCredential("apikey", "k");
            }

            Directory.CreateDirectory(Path.Combine(_dir.Path, "tools"));
            File.WriteAllText(Path.Combine(_dir.Path, "tools", "uv.exe"), "");
            var engine = new ProjectEngine(new Runner(this, hash), new ToolLocator(_dir.Path)) { RepositoryPath = _dir.Path };
            Wiki = new WikiPublisher(new PanoramaSignIn(store, Server), engine, new WorkTracker(NullLogger<WorkTracker>.Instance),
                new AppPaths(_dir.Path), NullLogger<WikiPublisher>.Instance) { Handler = Handler };
        }

        public StubHandler Handler { get; }

        public WikiPublisher Wiki { get; }

        public string Html { get; }

        /// <summary>The --documents JSON the engine was given.</summary>
        public string Documents { get; set; } = "";

        public ProjectSummary Project { get; } = new()
        {
            Project = "MNRF-BioTRACK",
            Wiki = new WikiLocation("/MacCoss/Collaborations/MNRF/BioTRACK", "default"),
            Experiments =
            [
                new ExperimentSummary
                {
                    Experiment = "2026-09-BioTRACK-DIA", Status = "active",
                    Panorama =
                    [
                        new PanoramaFolder("/MacCoss/Collaborations/MNRF/BioTRACK/2026-09-BioTRACK-Quant/@files/RawFiles", "raw"),
                        new PanoramaFolder("/MacCoss/Collaborations/MNRF/BioTRACK/2026-09-BioTRACK-Quant", "results"),
                    ],
                },
            ],
        };

        public void Dispose() => _dir.Dispose();

        private sealed class Runner(Publisher owner, string hash) : IProcessRunner
        {
            public Task<ProcessResult> RunAsync(
                string fileName, IEnumerable<string> arguments, string? workingDirectory = null,
                IReadOnlyDictionary<string, string?>? environment = null, TimeSpan? timeout = null,
                CancellationToken cancellationToken = default)
            {
                var args = arguments.ToList();
                var documents = args.IndexOf("--documents");
                if (documents >= 0)
                {
                    owner.Documents = File.ReadAllText(args[documents + 1]);
                }

                var json = JsonSerializer.Serialize(new
                {
                    ok = true, project = "MNRF-BioTRACK", folder = "/MacCoss/Collaborations/MNRF/BioTRACK", page = "default",
                    title = "MNRF BioTRACK", html = owner.Html, written = true, written_hash = hash,
                });
                return Task.FromResult(new ProcessResult(0, json, ""));
            }
        }
    }

    private sealed class Store : ICredentialStore
    {
        public Dictionary<string, StoredCredential> Entries { get; } = [];

        public StoredCredential? Read(string target) => Entries.TryGetValue(target, out var c) ? c : null;

        public void Write(string target, StoredCredential credential, string comment) => Entries[target] = credential;

        public void Delete(string target) => Entries.Remove(target);
    }

    private sealed class StubHandler(Func<HttpRequestMessage, HttpResponseMessage> respond) : HttpMessageHandler
    {
        public List<HttpRequestMessage> Requests { get; } = [];

        /// <summary>The JSON of each POST.</summary>
        public List<JsonElement> Bodies { get; } = [];

        protected override async Task<HttpResponseMessage> SendAsync(HttpRequestMessage request, CancellationToken cancellationToken)
        {
            Requests.Add(request);
            if (request.Content is not null)
            {
                Bodies.Add(JsonDocument.Parse(await request.Content.ReadAsStringAsync(cancellationToken)).RootElement.Clone());
            }

            return respond(request);
        }
    }
