    private static readonly Uri Server = new("https://panoramaweb.org");

    /// <summary>The form of Panorama's wiki editor (captured from wiki-edit.view on panoramaweb.org, body shortened).</summary>
    private static string Editor(string body, int version = 18161) => $$"""
        <script type="text/javascript" nonce="b51d5557448bff2f">
            LABKEY._wiki.setProps({
                entityId: '9e9d2b09-a24f-103f-94c2-1cc91aa92d00',
                rowId: 4328,
                name: 'default',
                title: 'MNRF BioTRACK',
                body: '{{body}}',
                parent: null,
                pageVersionId: {{version}},
                rendererType: 'HTML',
                webPartId: 0,
                showAttachments: true,
                shouldIndex: true,
                isDirty: false,
                useVisualEditor: true
            });
            LABKEY._wiki.setAttachments([
            ]);
        </script>
        """;

    private const string HandWritten = @"\x3Cdiv style=\""max-width:1050px\""\x3E\n\x3Cp\x3EIt\'s 200 µL\x3C/p\x3E\x3C/div\x3E";

    private static string Ours(string hash) =>
        $@"\x3Cdiv\x3E\x3Cp\x3EProgress\x3C/p\x3E\n\x3Cdiv id=\""chargestate-wiki\"" data-written=\""{hash}\"" style=\""x\""\x3EGenerated by ChargeState\x3C/div\x3E\x3C/div\x3E";

    /// <summary>ChargeState's page with a fingerprint of the text above the footer that no longer matches it.</summary>
    private const string EditedOnPanorama =
        @"\x3Cdiv\x3E\x3Cp\x3EEdited by hand\x3C/p\x3E\n\x3Cdiv id=\""chargestate-wiki\"" data-written=\""abc\"" data-body=\""000000000000\""\x3EGenerated\x3C/div\x3E\x3C/div\x3E";

    private const string Runs = """
        {"rowCount":1,"rows":[{"FileName":"2026-09-BioTRACK-initial-plate1_2026-10-01_23-38-45.sky.zip","ReplicateCount":89,
         "PeptideCount":84806,"PeptideGroupCount":6746,"Created":"2026-10-01 23:42:20.311"}]}
        """;

    // -- Panorama ------------------------------------------------------------------------------

    [Fact]
    public void The_editor_gives_the_page_its_version_and_its_text()
    {
        var page = PanoramaClient.ParseWikiEditor(Editor(HandWritten));

        page.EntityId.ShouldBe("9e9d2b09-a24f-103f-94c2-1cc91aa92d00");
        (page.RowId, page.PageVersionId, page.Parent, page.Name, page.Title).ShouldBe((4328, 18161, (int?)null, "default", "MNRF BioTRACK"));
        page.Body.ShouldBe("<div style=\"max-width:1050px\">\n<p>It's 200 µL</p></div>");
        page.IsChargeState.ShouldBeFalse();
        page.WrittenHash.ShouldBeNull();

        var ours = PanoramaClient.ParseWikiEditor(Editor(Ours("3f2a9c01b7de")));
        ours.IsChargeState.ShouldBeTrue();
        ours.WrittenHash.ShouldBe("3f2a9c01b7de");
    }

    [Fact]
    public void An_editor_that_cannot_be_read_leaves_the_page_alone()
    {
        Should.Throw<PanoramaException>(() => PanoramaClient.ParseWikiEditor("<html>Sign in</html>")).Message.ShouldContain("left alone");
        Should.Throw<PanoramaException>(() => PanoramaClient.ParseWikiEditor("LABKEY._wiki.setProps({\n entityId: '',\n});"))
            .Message.ShouldContain("left alone");
    }

    [Fact]
    public void A_page_edited_on_Panorama_after_it_was_published_is_recognized()
    {
        const string above = "<div><p>Progress</p>\n";
        var hash = Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(above)))[..12];
        static WikiPageInfo Page(string body) => new("e", 1, 2, "default", "T", body, null, true, true);
        var published = above + $"<div id=\"chargestate-wiki\" data-written=\"abc\" data-body=\"{hash}\">Generated</div>\n</div>\n";

        Page(published).EditedOnPanorama.ShouldBeFalse();
        Page(published.Replace("Progress", "Progress, and a sentence added on Panorama", StringComparison.Ordinal)).EditedOnPanorama.ShouldBeTrue();
        Page(above + "<div id=\"chargestate-wiki\" data-written=\"abc\">Generated</div>").EditedOnPanorama.ShouldBeFalse();  // before fingerprints
        Page("<p>by hand</p>").EditedOnPanorama.ShouldBeFalse();
    }

