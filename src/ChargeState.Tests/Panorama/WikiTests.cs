    /// <summary>Panorama's login-whoami.api: the session's CSRF token, and the session's cookies.</summary>
    private static HttpResponseMessage WhoAmI()
    {
        var response = Json("""{"id":1694,"displayName":"someone","CSRF":"t0k3n"}""");
        response.Headers.Add("Set-Cookie", "JSESSIONID=abc123; Path=/; Secure; HttpOnly");
        response.Headers.Add("Set-Cookie", "X-LABKEY-CSRF=t0k3n; Path=/; Secure");
        return response;
    }

    [Fact]
    public async Task Saving_names_the_version_it_replaces_and_reads_the_new_one()
    {
        var handler = new StubHandler(r => r.RequestUri!.AbsolutePath == "/login-whoami.api"
            ? WhoAmI()
            : Json("""{"success":true,"wikiProps":{"entityId":"9e9d","rowId":4328,"pageVersionId":18200}}"""));
        using var client = new PanoramaClient(Server, PanoramaCredential.ApiKey("k"), handler);
        var existing = PanoramaClient.ParseWikiEditor(Editor(HandWritten));

        var saved = await client.SaveWikiPageAsync("/MacCoss/Collaborations/MNRF/BioTRACK", "default", "MNRF BioTRACK", "<div>new</div>", existing);

        saved.PageVersionId.ShouldBe(18200);
        // LabKey wants a CSRF token on a POST, even with an API key: it comes from whoami, with the session's cookies.
        handler.Requests.Select(r => r.Method.Method).ShouldBe(["GET", "POST"]);
        var request = handler.Requests[1];
        request.Headers.GetValues("X-LABKEY-CSRF").Single().ShouldBe("t0k3n");
        request.Headers.GetValues("Cookie").Single().ShouldBe("JSESSIONID=abc123; X-LABKEY-CSRF=t0k3n");
        request.Headers.Authorization.ShouldNotBeNull();
        request.Method.ShouldBe(HttpMethod.Post);
        request.RequestUri!.AbsolutePath.ShouldBe("/MacCoss/Collaborations/MNRF/BioTRACK/wiki-saveWiki.api");
        var sent = handler.Bodies.Single();
        sent.GetProperty("entityId").GetString().ShouldBe("9e9d2b09-a24f-103f-94c2-1cc91aa92d00");
        sent.GetProperty("pageVersionId").GetInt32().ShouldBe(18161);
        sent.GetProperty("rendererType").GetString().ShouldBe("HTML");
        sent.GetProperty("body").GetString().ShouldBe("<div>new</div>");
    }

    [Fact]
    public async Task A_new_page_is_saved_without_an_id_and_a_refusal_says_why()
    {
        var handler = new StubHandler(_ => new HttpResponseMessage(HttpStatusCode.BadRequest)
        {
            Content = new StringContent("""{"exception":"Someone else has edited this page since you started.","success":false}"""),
        });
        using var client = new PanoramaClient(Server, PanoramaCredential.ApiKey("k"), handler);

        var ex = await Should.ThrowAsync<PanoramaException>(() => client.SaveWikiPageAsync("/MacCoss/x", "default", "T", "<p/>", null));

        ex.Message.ShouldBe("Panorama refused the wiki page default in /MacCoss/x: Someone else has edited this page since you started.");
        handler.Bodies.Single().GetProperty("entityId").ValueKind.ShouldBe(JsonValueKind.Null);
        handler.Bodies.Single().GetProperty("name").GetString().ShouldBe("default");
    }

