    [Fact]
    public void The_window_says_what_publishing_would_do()
    {
        var content = new WikiPageContent("P", "/MacCoss/x", "default", "T", "<div/>", Written: true, WrittenHash: "abc");
        var ours = PanoramaClient.ParseWikiEditor(Editor(Ours("abc")));

        WikiViewModel.Describe(false, null, content).ShouldStartWith("Not signed in to Panorama");
        WikiViewModel.Describe(true, null, content).ShouldStartWith("Not on Panorama yet.");
        WikiViewModel.Describe(true, PanoramaClient.ParseWikiEditor(Editor(HandWritten)), content).ShouldContain("written by hand");
        WikiViewModel.Describe(true, ours, content).ShouldBe("On Panorama, and updated by the app after every change.");
        WikiViewModel.Describe(true, ours, content with { WrittenHash = "def" }).ShouldContain("The text has changed");
        WikiViewModel.Describe(true, ours, content with { Written = false }).ShouldContain("Write the text with Claude");
        WikiViewModel.Describe(true, PanoramaClient.ParseWikiEditor(Editor(EditedOnPanorama)), content).ShouldContain("was edited there");
        WikiViewModel.Document("<p>x</p>", "https://panoramaweb.org/MacCoss/x/wiki-page.view?name=default")
            .ShouldContain("<base href=\"https://panoramaweb.org/MacCoss/x/wiki-page.view?name=default\">");
    }

    [Fact]
    public async Task After_a_change_the_app_updates_its_own_page_with_the_Skyline_documents()
    {
        using var setup = new Publisher(Editor(Ours("abc")), hash: "abc");

        var notice = await setup.Wiki.UpdateAsync(setup.Project);

        notice.ShouldNotBeNull().ShouldStartWith("Wiki page for MNRF-BioTRACK updated");
        var save = setup.Handler.Bodies.Single();
        save.GetProperty("pageVersionId").GetInt32().ShouldBe(18161);
        save.GetProperty("body").GetString().ShouldBe(setup.Html);
        // The results folder's documents went to the engine.
        setup.Documents.ShouldContain("2026-09-BioTRACK-initial-plate1");
        setup.Documents.ShouldContain("\"replicates\":89");
    }

    [Fact]
    public async Task A_page_written_by_hand_or_new_text_waits_for_a_person()
    {
        using (var handWritten = new Publisher(Editor(HandWritten), hash: "abc"))
        {
            (await handWritten.Wiki.UpdateAsync(handWritten.Project)).ShouldBeNull();
            handWritten.Handler.Bodies.ShouldBeEmpty();
        }

        using (var newText = new Publisher(Editor(Ours("abc")), hash: "def"))
        {
            (await newText.Wiki.UpdateAsync(newText.Project)).ShouldNotBeNull().ShouldContain("open Wiki page to review and publish it");
            newText.Handler.Bodies.ShouldBeEmpty();
        }

        using (var edited = new Publisher(Editor(EditedOnPanorama), hash: "abc"))
        {
            (await edited.Wiki.UpdateAsync(edited.Project)).ShouldNotBeNull().ShouldContain("edited on Panorama since the app published it");
            edited.Handler.Bodies.ShouldBeEmpty();
        }

        using var missing = new Publisher(editor: null, hash: "abc");
        (await missing.Wiki.UpdateAsync(missing.Project)).ShouldBeNull();
        missing.Handler.Bodies.ShouldBeEmpty();
    }

